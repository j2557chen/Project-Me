    private val libraryNames = ExerciseLibrary.all.map { it.name }

    @Test
    fun everyHevyAppExerciseIsInTheLibrary() {
        val lower = libraryNames.map { it.lowercase() }.toSet()
        hevyCatalog.forEach { hevy ->
            val name = ExerciseLibrary.HEVY_ALIASES[hevy] ?: hevy
            assertTrue("$hevy isn't in the library", name.lowercase() in lower)
        }
    }

    @Test
    fun catalogRenamesPointAtLibraryNames() {
        val names = libraryNames.toSet()
        ExerciseLibrary.CATALOG_RENAMES.forEach { (old, new) ->
            assertTrue("$new isn't in the library", new in names)
            assertTrue("$old is still in the library", old !in names)
        }
    }

    @Test
    fun renamesPointAtLibraryNamesAndLeaveNoOldOnes() {
        val names = libraryNames.toSet()
        ExerciseLibrary.LIBRARY_RENAMES.forEach { (old, new) ->
            assertTrue("$new isn't in the library", new in names)
            assertTrue("$old is still in the library", old !in names)
        }
        ExerciseLibrary.HEVY_ALIASES.values.forEach { assertTrue("$it isn't in the library", it in names) }
    }

    @Test
    fun namesAreUnique() {
        assertTrue(libraryNames.size == libraryNames.toSet().size)
    }
